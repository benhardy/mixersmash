//go:build ignore

// gen_connections generates the paletteConnectionNames map for creatures.go.
//
// The connection graph is directed: each node i has exactly Power[i] outgoing
// edges to distinct other nodes (no self-links, no duplicate targets).
// Connections are chosen deterministically from seed 42: for each node, in
// descending Power order (ties broken by palette index), pick Power distinct
// targets by sampling without replacement from all other nodes using the
// seeded PRNG.
//
// Operates on organism names (string keys); no Organism type reference needed.
//
// Run with: go run tools/gen_connections/main.go
package main

import (
	"fmt"
	"math/rand"
	"sort"
)

var names = []string{
	"kangaroo", "koala", "cat", "wolf", "horse", "butterfly", "snake",
	"dragon", "ghost", "fish", "dolphin", "octopus", "monkey", "bat",
	"pig", "owl", "frog", "turtle", "crab", "honeybee", "spider",
	"elephant", "penguin",
}

var powers = []int{
	8, // kangaroo (index 0)
	5, // koala    (index 1)
	5, // cat      (index 2)
	5, // wolf     (index 3)
	3, // horse    (index 4)
	3, // butterfly(index 5)
	3, // snake    (index 6)
	3, // dragon   (index 7)
	3, // ghost    (index 8)
	3, // fish     (index 9)
	2, // dolphin  (index 10)
	2, // octopus  (index 11)
	2, // monkey   (index 12)
	2, // bat      (index 13)
	2, // pig      (index 14)
	2, // owl      (index 15)
	2, // frog     (index 16)
	2, // turtle   (index 17)
	2, // crab     (index 18)
	2, // honeybee (index 19)
	2, // spider   (index 20)
	2, // elephant (index 21)
	2, // penguin  (index 22)
}

func main() {
	n := len(names)
	rng := rand.New(rand.NewSource(42))

	// Process nodes in descending Power order (ties: ascending index).
	order := make([]int, n)
	for i := range order {
		order[i] = i
	}
	sort.Slice(order, func(a, b int) bool {
		if powers[order[a]] != powers[order[b]] {
			return powers[order[a]] > powers[order[b]]
		}
		return order[a] < order[b]
	})

	adj := make([][]int, n)

	for _, i := range order {
		k := powers[i]
		// Candidates: all nodes except self.
		candidates := make([]int, 0, n-1)
		for j := 0; j < n; j++ {
			if j != i {
				candidates = append(candidates, j)
			}
		}
		// Fisher-Yates shuffle candidates.
		rng.Shuffle(len(candidates), func(a, b int) {
			candidates[a], candidates[b] = candidates[b], candidates[a]
		})
		// Take first k.
		chosen := candidates[:k]
		// Sort for deterministic output order.
		sort.Ints(chosen)
		adj[i] = chosen
	}

	fmt.Printf("// paletteConnectionNames generated by tools/gen_connections/main.go\n")
	fmt.Printf("// Seed: 42. Directed graph; each node has exactly Power outgoing edges.\n")
	fmt.Printf("var paletteConnectionNames = map[string][]string{\n")
	for i, name := range names {
		fmt.Printf("\t%q: {", name)
		for c, nb := range adj[i] {
			if c > 0 {
				fmt.Printf(", ")
			}
			fmt.Printf("%q", names[nb])
		}
		fmt.Printf("},\n")
	}
	fmt.Printf("}\n")
}
