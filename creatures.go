func (randomTheme) name() string { return "random" }

func (randomTheme) instructions() string {
	return "Learn which creatures connect"
}

func (randomTheme) assign(palette []Creature) (powers []int, conns [][]int) {
	// Build name→index map.
	nameIndex := make(map[string]int, len(palette))
	for i := range palette {
		nameIndex[palette[i].Name] = i
	}

	powers = make([]int, len(palette))
	conns = make([][]int, len(palette))
	for i := range palette {
		powers[i] = palette[i].Power // preserve existing Fibonacci power
		names := paletteConnectionNames[palette[i].Name]
		indices := make([]int, len(names))
		for c, n := range names {
			indices[c] = nameIndex[n]
		}
		conns[i] = indices
	}
	return powers, conns
}

// colourTheme returns the same Fibonacci power baseline as the palette literal,
// and for each creature assigns its Power nearest neighbours by OKLab colour
// distance. Ties are broken by ascending palette index (deterministic).
type colourTheme struct{}

func (colourTheme) name() string { return "colour" }

func (colourTheme) instructions() string {
	return "Connect creatures of similar colour"
}

func (colourTheme) assign(palette []Creature) (powers []int, conns [][]int) {
	n := len(palette)

	// Convert all palette colours to OKLab once.
	labs := make([][3]float64, n)
	for i := range palette {
		labs[i] = sRGBToOKLab(palette[i].Color)
	}

	powers = make([]int, n)
	conns = make([][]int, n)
	for i := range palette {
		powers[i] = palette[i].Power
		k := palette[i].Power // number of nearest neighbours == power

		// Build a sorted list of (distance, index) for all j != i.
		type distIdx struct {
			dist float64
			idx  int
		}
		others := make([]distIdx, 0, n-1)
		for j := range palette {
			if j == i {
				continue
			}
			dl := labs[i][0] - labs[j][0]
			da := labs[i][1] - labs[j][1]
			db := labs[i][2] - labs[j][2]
			dist := math.Sqrt(dl*dl + da*da + db*db)
			others = append(others, distIdx{dist, j})
		}
		// Sort by distance ascending; break ties by index ascending.
		sort.Slice(others, func(a, b int) bool {
			if others[a].dist != others[b].dist {
				return others[a].dist < others[b].dist
			}
			return others[a].idx < others[b].idx
		})

		// Take first k.
		indices := make([]int, k)
		for c := 0; c < k; c++ {
			indices[c] = others[c].idx
		}
		conns[i] = indices
	}
	return powers, conns
}

// sRGBToOKLab converts a colour.RGBA to OKLab [L, a, b].
// Used only at theme-build time (not per frame).
// Reference: https://bottosson.github.io/posts/oklab/
func sRGBToOKLab(c color.RGBA) [3]float64 {
	// Linear sRGB (gamma expand).
	toLinear := func(u uint8) float64 {
		s := float64(u) / 255.0
		if s <= 0.04045 {
			return s / 12.92
		}
		return math.Pow((s+0.055)/1.055, 2.4)
	}
	r := toLinear(c.R)
	g := toLinear(c.G)
	b := toLinear(c.B)

	// Linear sRGB → LMS (OKLab M1 matrix).
	l := 0.4122214708*r + 0.5363325363*g + 0.0514459929*b
	m := 0.2119034982*r + 0.6806995451*g + 0.1073969566*b
	s := 0.0883024619*r + 0.2817188376*g + 0.6299787005*b

	// Cube root.
	lc := math.Cbrt(l)
	mc := math.Cbrt(m)
	sc := math.Cbrt(s)

	// LMS → OKLab (OKLab M2 matrix).
	L := 0.2104542553*lc + 0.7936177850*mc - 0.0040720468*sc
	a := 1.9779984951*lc - 2.4285922050*mc + 0.4505937099*sc
	bk := 0.0259040371*lc + 0.7827717662*mc - 0.8086757660*sc

	return [3]float64{L, a, bk}
}

// setActiveTheme applies t to creaturePalette: writes new Power values, resolves
// connection index lists to *Creature pointers, and rebuilds the spawn CDF.
// Trivially switchable at runtime; level-based switching comes later.
func setActiveTheme(t connectionTheme) {
	activeTheme = t
	powers, conns := t.assign(creaturePalette)

	// Apply powers and connections.
	for i := range creaturePalette {
		creaturePalette[i].Power = powers[i]
		indices := conns[i]
		ptrs := make([]*Creature, len(indices))
		for c, j := range indices {
			ptrs[c] = &creaturePalette[j]
		}
		creaturePalette[i].Connections = ptrs
	}

	// Rebuild spawn CDF from updated powers (weight = 1/Power).
	n := len(creaturePalette)
	weights := make([]float64, n)
	var total float64
	for i := range creaturePalette {
		weights[i] = 1.0 / float64(creaturePalette[i].Power)
		total += weights[i]
	}
	paletteCDF = make([]float64, n)
	var cumulative float64
	for i, w := range weights {
		cumulative += w / total
		paletteCDF[i] = cumulative
	}
}

func init() {
	// Apply the default theme (colour-nearest). This replaces the old init()
	// that hardcoded connections from paletteConnectionNames directly.
	setActiveTheme(activeTheme)
}

// paletteCreature returns a pointer to a random entry in creaturePalette.
// Spawn probability is proportional to 1/Power (lower-power creatures appear
// more frequently). The pointer is stable because creaturePalette is a
// package-level slice that is never reallocated after init.
func paletteCreature() *Creature {
	x := rand.Float64()
	i := sort.SearchFloat64s(paletteCDF, x)
	if i >= len(creaturePalette) {
		i = len(creaturePalette) - 1
	}
	return &creaturePalette[i]
}

// darkerShade returns c with each channel multiplied by 0.65 (integer floor) and
// alpha forced to 255.
func darkerShade(c color.RGBA) color.RGBA {
	return color.RGBA{
		R: uint8(float64(c.R) * 0.15),
		G: uint8(float64(c.G) * 0.15),
		B: uint8(float64(c.B) * 0.15),
		A: 255,
	}
}

// loadGlyphFont parses the embedded NotoEmoji TTF and returns a GoTextFaceSource.
func loadGlyphFont() (*text.GoTextFaceSource, error) {
	src, err := text.NewGoTextFaceSource(bytes.NewReader(notoEmojiTTF))
	if err != nil {
		return nil, err
	}
	return src, nil
}
