// paletteCDF holds the normalised cumulative distribution function for
// weighted creature spawning (weight = 1/Power). Rebuilt by setActiveTheme.
var paletteCDF []float64

// connectionTheme assigns Power values and connection lists to the palette.
// Switching themes lets level-based mechanics rewire the creature graph without
// touching connectionVictims or any per-cell logic.
//
// assign receives the full palette slice and returns:
//   - powers: len(palette) ints; powers[i] is the new Power for palette[i].
//   - conns:  len(palette) index lists; conns[i] holds palette indices that
//     palette[i] connects to; len(conns[i]) must equal powers[i]; no self-index,
//     no duplicates within a row.
//
// instructions returns a short player-facing hint string explaining how
// connections work for this theme. Must be non-empty.
type connectionTheme interface {
	name() string
	instructions() string
	assign(palette []Creature) (powers []int, conns [][]int)
}

// activeTheme is the theme applied at startup and whenever setActiveTheme is
// called. Default is colourTheme (level-1 experience). Level-based switching
// can be added later by calling setActiveTheme with a different theme.
var activeTheme connectionTheme = colourTheme{}

